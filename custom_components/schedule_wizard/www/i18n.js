export const RTL_LANGS = ["he", "ar", "fa", "ur"];

const baseLang = (l) => String(l || "").toLowerCase().split("-")[0];

export function resolveLang(hass) {
  const raw = String((hass && ((hass.locale && hass.locale.language) || hass.language)) || "en").toLowerCase();
  if (STRINGS[raw]) return raw;
  const b = baseLang(raw);
  return STRINGS[b] ? b : "en";
}

export function makeT(lang) {
  const dict = STRINGS[lang] || {};
  const en = STRINGS.en;
  const t = (key, vars) => {
    // Singular form: "<key>_one" when n === 1 (e.g. Hebrew "לפני יום" instead of "לפני 1 ימים").
    if (vars && Number(vars.n) === 1 && Object.prototype.hasOwnProperty.call(en, key + "_one")) key += "_one";
    let s = dict[key] ?? en[key] ?? key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
    }
    return s;
  };
  t.has = (key) => Object.prototype.hasOwnProperty.call(en, key);
  t.lang = lang;
  return t;
}

// Split a template into text and nodes so placeholder values can be DOM nodes (e.g. <bdi>).
export function tnodes(template, vars) {
  const out = [];
  let last = 0;
  String(template).replace(/\{(\w+)\}/g, (m, k, off) => {
    if (off > last) out.push(template.slice(last, off));
    const v = vars ? vars[k] : undefined;
    out.push(v === undefined || v === null ? m : (typeof Node !== "undefined" && v instanceof Node ? v : String(v)));
    last = off + m.length;
    return m;
  });
  if (last < template.length) out.push(template.slice(last));
  return out;
}

export function isRtl(hass, lang) {
  const hl = hass && ((hass.locale && hass.locale.language) || hass.language);
  const meta = hass && hass.translationMetadata && hass.translationMetadata.translations;
  if (hl && meta && meta[hl] && meta[hl].isRTL === true) return true;
  return RTL_LANGS.includes(baseLang(lang));
}

const _fmtCache = new Map();

function _ctx(lang, hass) {
  const locale = (hass && ((hass.locale && hass.locale.language) || hass.language)) || lang || "en";
  let hour12;
  const tf = hass && hass.locale && hass.locale.time_format;
  if (tf === "12") hour12 = true;
  else if (tf === "24") hour12 = false;
  else if (tf === "system") {
    try { hour12 = new Intl.DateTimeFormat(undefined, { hour: "numeric" }).resolvedOptions().hour12; } catch (e) { hour12 = undefined; }
  }
  const tz = hass && hass.config && hass.config.time_zone;
  const timeZone = tz && !(hass.locale && hass.locale.time_zone === "local") ? tz : undefined;
  return { locale, hour12, timeZone };
}

function _dtf(locale, options) {
  const key = locale + "|" + JSON.stringify(options);
  let f = _fmtCache.get(key);
  if (f) return f;
  try {
    f = new Intl.DateTimeFormat(locale, options);
  } catch (e) {
    const rest = Object.assign({}, options);
    delete rest.timeZone;
    try { f = new Intl.DateTimeFormat(locale, rest); } catch (e2) { f = new Intl.DateTimeFormat("en", rest); }
  }
  _fmtCache.set(key, f);
  return f;
}

function _format(ts, lang, opts, defaults) {
  if (ts === null || ts === undefined || ts === "" || isNaN(Number(ts))) return "";
  const o = Object.assign({}, opts || {});
  const hass = o.hass;
  delete o.hass;
  const options = Object.keys(o).length ? o : Object.assign({}, defaults);
  const c = _ctx(lang, hass);
  if (c.hour12 !== undefined && options.hour !== undefined && options.hour12 === undefined) options.hour12 = c.hour12;
  if (c.timeZone && !options.timeZone) options.timeZone = c.timeZone;
  return _dtf(c.locale, options).format(new Date(Number(ts) * 1000));
}

// ts is unix seconds. opts may carry `hass` plus any Intl.DateTimeFormat options.
export function fmtDateTime(ts, lang, opts) {
  return _format(ts, lang, opts, { year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" });
}

export function fmtTime(ts, lang, opts) {
  return _format(ts, lang, opts, { hour: "numeric", minute: "2-digit" });
}

export function fmtDate(ts, lang, opts) {
  return _format(ts, lang, opts, { year: "numeric", month: "short", day: "numeric" });
}

// Stable per-day bucket key in the same time zone the formatters use.
export function dayKey(ts, hass) {
  const c = _ctx("en", hass);
  const options = { year: "numeric", month: "2-digit", day: "2-digit" };
  if (c.timeZone) options.timeZone = c.timeZone;
  return _dtf("en-CA", options).format(new Date(Number(ts) * 1000));
}

function _weekday(i, lang, opts, style) {
  const hass = opts && opts.hass;
  const c = _ctx(lang, hass);
  const d = new Date(Date.UTC(2024, 0, 1 + (((Number(i) % 7) + 7) % 7), 12));
  // Hebrew "short" weekdays are full words ("יום ב׳"); the narrow form ("ב׳") is the usual abbreviation.
  const effective = style === "short" && /^he(-|$)/i.test(c.locale) ? "narrow" : style;
  return _dtf(c.locale, { weekday: effective, timeZone: "UTC" }).format(d);
}

// dayIndexMon0: 0 = Monday ... 6 = Sunday (matches the backend day mask bit order).
export function weekdayShort(dayIndexMon0, lang, opts) {
  return _weekday(dayIndexMon0, lang, opts, "short");
}

export function weekdayLong(dayIndexMon0, lang, opts) {
  return _weekday(dayIndexMon0, lang, opts, "long");
}
